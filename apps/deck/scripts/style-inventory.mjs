import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, relative, resolve } from "node:path";

const deckRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = resolve(deckRoot, "../..");
const srcRoot = join(deckRoot, "src");
const outputPath = join(repoRoot, "docs", "tailwind-migration-inventory.md");
const colorPattern = /#[0-9a-fA-F]{3,8}|rgba?\(|hsla?\(|oklch\(/gu;

function toPosix(path) {
  return path.replaceAll("\\", "/");
}

function walkCssFiles(dir) {
  return readdirSync(dir).flatMap((entry) => {
    const path = join(dir, entry);
    const stats = statSync(path);
    if (stats.isDirectory()) {
      return walkCssFiles(path);
    }
    return path.endsWith(".css") ? [path] : [];
  });
}

function countLines(source) {
  if (source.length === 0) {
    return 0;
  }
  return source.split(/\r?\n/u).length;
}

function extractSelectors(source) {
  const selectors = new Set();
  const pattern = /(?:^|\})\s*([^{}@][^{]*?)\s*\{/gsu;
  for (const match of source.matchAll(pattern)) {
    const selectorBlock = match[1]
      .replace(/\/\*[\s\S]*?\*\//gu, "")
      .trim();
    if (!selectorBlock || selectorBlock.includes(";")) {
      continue;
    }
    for (const selector of selectorBlock.split(",")) {
      const normalized = selector.trim().replace(/\s+/gu, " ");
      if (normalized) {
        selectors.add(normalized);
      }
    }
  }
  return [...selectors].sort((a, b) => a.localeCompare(b));
}

function extractHardCodedColors(source) {
  return [...new Set(source.match(colorPattern) ?? [])].sort((a, b) =>
    a.localeCompare(b),
  );
}

const files = walkCssFiles(srcRoot)
  .map((path) => {
    const source = readFileSync(path, "utf8");
    return {
      path,
      displayPath: toPosix(relative(repoRoot, path)),
      lineCount: countLines(source),
      selectors: extractSelectors(source),
      colors: extractHardCodedColors(source),
    };
  })
  .sort((a, b) => a.displayPath.localeCompare(b.displayPath));

const totalLines = files.reduce((sum, file) => sum + file.lineCount, 0);
const lines = [
  "# Tailwind Migration CSS Inventory",
  "",
  "> Generated by `node apps/deck/scripts/style-inventory.mjs`.",
  "",
  "## Summary",
  "",
  `- CSS files: ${files.length}`,
  `- Total lines: ${totalLines}`,
  "",
  "## Files",
  "",
];

for (const file of files) {
  lines.push(`### ${file.displayPath}`);
  lines.push("");
  lines.push(`- Lines: ${file.lineCount}`);
  lines.push(`- Top-level selectors: ${file.selectors.length}`);
  lines.push(`- Hard-coded color tokens: ${file.colors.length}`);
  lines.push("");
  if (file.selectors.length > 0) {
    lines.push("Selectors:");
    lines.push("");
    for (const selector of file.selectors) {
      lines.push(`- \`${selector}\``);
    }
    lines.push("");
  }
  if (file.colors.length > 0) {
    lines.push("Hard-coded colors:");
    lines.push("");
    for (const color of file.colors) {
      lines.push(`- \`${color}\``);
    }
    lines.push("");
  }
}

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, `${lines.join("\n")}\n`, "utf8");
console.log(`wrote ${toPosix(relative(repoRoot, outputPath))} (${files.length} CSS files)`);
